SELECT
    ROW_NUMBER() OVER (ORDER BY p.id) AS id,
    p.id,
    CASE
        WHEN p.is_featured THEN 220 + (p.id * 7 % 180)
        WHEN p.category_id IN (16, 17) THEN 180 + (p.id * 11 % 240)
        WHEN p.category_id IN (21, 22) THEN 12 + (p.id * 3 % 25)
        ELSE 35 + (p.id * 13 % 130)
